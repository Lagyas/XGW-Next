"""Record the git commit and build date in editor/build_info.py (run before
PyInstaller; the file is not committed). Usage: python tools/write_build_info.py"""
import datetime
import platform
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


commit = git("rev-parse", "--short", "HEAD") or "unknown"
dirty = bool(git("status", "--porcelain", "--untracked-files=no"))
date = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
target = ROOT / "editor" / "build_info.py"
target.write_text(
    '"""Generated by tools/write_build_info.py — do not edit or commit."""\n'
    f"COMMIT = {commit!r}\nDIRTY = {dirty!r}\nBUILD_DATE = {date + ' on ' + platform.system()!r}\n",
    encoding="utf-8")
print(f"build info: {commit}{' (dirty)' if dirty else ''}, {date}")
